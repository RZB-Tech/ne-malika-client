/**
 * Зерно порядка витрины.
 *
 * Каталог показывается вперемешку, и порядок задаёт не сервер сам по себе, а
 * это зерно: с одним и тем же зерном сервер возвращает один и тот же порядок,
 * поэтому вторая страница ленты продолжает первую, а не тасуется заново.
 *
 * Заводится один раз на заход — при перезагрузке страницы витрина оказывается
 * перемешана по-новому, а при переходе по разделам без перезагрузки порядок
 * остаётся тем же, каким покупатель его увидел.
 *
 * Восемь знаков из base36 — вариантов на несколько порядков больше, чем
 * заходов на витрину; длиннее незачем, зерно едет в адресе запроса.
 */
export function randomCatalogSeed(): string {
  return `${Math.random().toString(36).slice(2)}00000000`.slice(0, 8);
}
